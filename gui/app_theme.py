class AppTheme:
    def __init__(self,
                 title_pad_x: int,
                 title_pad_y: int,
                 label_pad_x: int,
                 label_pad_y: int,
                 control_pad_x: int,
                 control_pad_y: int):
        self.title_pad_x = title_pad_x
        self.title_pad_y = title_pad_y
        self.label_pad_x = label_pad_x
        self.label_pad_y = label_pad_y
        self.control_pad_x = control_pad_x
        self.control_pad_y = control_pad_y